    internal fun parseEarbudFirmwareVersion(version: String?): Int? {
        if (version.isNullOrBlank()) return null
        val fields = version.split(',').map(String::trim)
        val versions = mutableListOf<Int>()
        var i = 0
        while (i + 2 < fields.size) {
            val component = fields[i].toIntOrNull()
            val value = fields[i + 2].trimStart('0').ifEmpty { "0" }.toIntOrNull()
            if (component in 1..2 && value != null) versions += value
            i += 3
        }
        return versions.minOrNull()
    }
